_MANIFEST_RULES: dict[str, Any] = {
    "if": {
        "properties": {
            "content": {
                "properties": {"content_kind": {"const": "rows"}},
                "required": ["content_kind"],
            }
        },
        "required": ["content"],
    },
    "then": {"properties": {"sources": {"minItems": 1}}},
}


class DatasetVersionManifest(_Strict):
    """``midataworks.dataset-version/v1``: one document per published or exported version."""

    model_config = ConfigDict(
        extra="forbid",
        frozen=True,
        json_schema_extra=_MANIFEST_RULES,
        title=SCHEMA_TITLE,
    )

    kind: Literal["midataworks.dataset-version"]
    schema_version: Literal["1"]
    producer: Producer
    version: VersionIdentity
    target: Target
    sources: list[Source]
    content: Content
    caveats: list[Caveat]
    publication: Publication | None
    extensions: Extensions

    @model_validator(mode="after")
    def _rows_name_their_sources(self) -> DatasetVersionManifest:
        if isinstance(self.content, RowsContent) and not self.sources:
            raise ValueError("a rows manifest names at least one source")
        return self


def schema_document() -> dict[str, Any]:
    """The JSON Schema as a dict, with the header keys first."""
    generated = DatasetVersionManifest.model_json_schema()
    generated.pop("title", None)
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": SCHEMA_ID,
        "title": SCHEMA_TITLE,
        "description": SCHEMA_DESCRIPTION,
        **{k: v for k, v in generated.items() if k != "description"},
    }


def render_schema_file() -> bytes:
    """The exact bytes of ``docs/schemas/midataworks-dataset-version-v1.json``.

    Indented for people to read; it is compared byte for byte, never re-hashed in another form,
    so this does not breach the single-serialiser rule for manifests (FTDD 008 section 4.5).
    """
    return (json.dumps(schema_document(), indent=2, ensure_ascii=False) + "\n").encode("utf-8")
