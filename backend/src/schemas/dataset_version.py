"""The handoff contract ``midataworks.dataset-version/v1`` (FR-008.33–008.40; FTDD 008 section 4.5).

This module is the SOURCE of ``docs/schemas/midataworks-dataset-version-v1.json``. The file is
generated by :func:`render_schema_file` and written only by
``backend/scripts/write_dataset_version_schema.py``; ``test_dataset_version_schema_sync.py``
compares the two byte for byte. miStudio and miForge vendor the file byte-identical.

Model rules (each guards a defect the suite has already paid for):

- every model forbids extra keys, so the schema says ``additionalProperties: false`` everywhere
  except the named ``extensions`` points (T-39);
- no field has a default, so every field is ``required`` and an unknown fact is an explicit
  ``null`` or a literal such as ``"not stated"`` — never an omission and never a plausible guess;
- no field uses an alias (an alias renames on OUTPUT and once dropped a wire field from a
  published miStudio schema);
- every cross-field rule is written twice — a ``model_validator`` here and an ``if/then`` in the
  model's JSON Schema — so the published file refuses what Python refuses
  (``test_dataset_version_model.py`` feeds each violation to both).
"""

