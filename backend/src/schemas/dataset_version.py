class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


# --- identity -------------------------------------------------------------------------------


class Producer(_Strict):
    """The application and build that wrote the manifest (M-2)."""

    app: Literal["miDataworks"]
    build: NonEmpty
    generated_at: Timestamp


class RecipeRef(_Strict):
    format: Literal["dw.recipe/v1"]
    sha256: Sha256


class VersionIdentity(_Strict):
    """Which version this is and how it was made (M-2, M-6). Origin only; names stay inside."""

    dataset: Annotated[str, StringConstraints(pattern=r"^[a-z0-9][a-z0-9-]*$")]
    version_id: NonEmpty
    number: Annotated[int, Field(ge=1)]
    parent_version_id: str | None
    created_at: Timestamp
    created_by_origin: Literal["operator", "agent"]
    recipe: RecipeRef
    seed: int
    row_key_scheme: NonEmpty


class ContractReference(_Strict):
    """miForge renders ``<type>/<name>@<version>`` (M-4). No pack in v1 (P-25)."""

    type: NonEmpty
    name: NonEmpty
    version: NonEmpty


_TARGET_RULES: dict[str, Any] = {
    "allOf": [
        {
            "if": {"properties": {"kind": {"const": "trl_export"}}, "required": ["kind"]},
            "then": {
                "properties": {"trl_type": {"type": "string"}, "trl_version": {"type": "string"}}
            },
        },
        {
            "if": {"properties": {"kind": {"const": "detector_role"}}, "required": ["kind"]},
            "then": {"properties": {"detector_role": {"type": "string"}}},
        },
        {
            "if": {"properties": {"kind": {"const": "miforge_set"}}, "required": ["kind"]},
            "then": {"properties": {"miforge_set_kind": {"type": "string"}}},
        },
    ]
}


class Target(_Strict):
    """What the files are for (M-3, M-4)."""

    model_config = ConfigDict(extra="forbid", frozen=True, json_schema_extra=_TARGET_RULES)

    kind: TargetKind
    dataset_target_type: DatasetTargetType | None
    trl_type: TrlType | None
    trl_version: str | None
    detector_role: DetectorRole | None
    miforge_set_kind: MiforgeSetKind | None
    contract_reference: ContractReference | None

    @model_validator(mode="after")
    def _kind_needs_its_field(self) -> Target:
        if self.kind == "trl_export" and (self.trl_type is None or self.trl_version is None):
            raise ValueError("a trl_export target names its trl_type and trl_version")
        if self.kind == "detector_role" and self.detector_role is None:
            raise ValueError("a detector_role target names its detector_role")
        if self.kind == "miforge_set" and self.miforge_set_kind is None:
            raise ValueError("a miforge_set target names its miforge_set_kind")
        return self


