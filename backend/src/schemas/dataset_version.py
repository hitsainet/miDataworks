_COLUMN_RULES: dict[str, Any] = {
    "if": {"properties": {"semantic": {"const": "label"}}, "required": ["semantic"]},
    "then": {"properties": {"label_values": {"type": "array"}}},
}


class Column(_Strict):
    """A shipped column (M-9). A ``label`` column always lists its values."""

    model_config = ConfigDict(extra="forbid", frozen=True, json_schema_extra=_COLUMN_RULES)

    name: NonEmpty
    arrow_type: NonEmpty
    role: Literal["content", "metadata", "system"]
    semantic: Literal[
        "text",
        "messages",
        "prompt",
        "completion",
        "completions",
        "chosen",
        "rejected",
        "label",
        "labels",
        "probability",
        "reference",
        "group",
        "other",
    ]
    label_values: list[str] | None
    extensions: Extensions

    @model_validator(mode="after")
    def _label_lists_values(self) -> Column:
        if self.semantic == "label" and self.label_values is None:
            raise ValueError(f"label column {self.name!r} must list its label_values")
        return self


