"""The rebrand export loader for pytest (feature 020; FR-020.1; CF-1, CF-2, CF-15, CF-16, CF-21,
CF-24, CF-25 m4/m5; FTID §8.2).

``docs/legacy-identifiers.md`` (full) and ``docs/legacy-identifiers.public.md`` (public) are
GENERATED by the suite's ``census.py --export miDataworks``; never edited here. This loader is the
one reader every 020 test uses (the frozen-identifier meta test, the rename-table comparison, the
brand guard), and it refuses a file it does not fully understand, naming the offending field, so a
newer format or a typo fails loudly instead of being half read:

- a header whose ``format`` is not 1, an unknown header key, a header without ``closed``;
- an unknown ``section``, an unknown key in a record, a missing key;
- a flag outside the closed set (``history_only``, ``text_only``, ``public_withheld``, ``pending``);
- a status outside each section's vocabulary; an unknown phase name;
- a ``host`` record whose ``observed`` is not a boolean (CF-24);
- a ``guard`` ``effect`` other than ``deny``/``allow``;
- ``js_flags`` other than ``""``/``"i"``; a ``pattern_js`` with an inline flag group
  (``\\(\\?[a-zA-Z]+[:)]``; lookarounds and ``(?:`` are legal, CF-25 m4);
- a ``pattern`` using ``\\A``, ``\\Z``, ``(?P`` or ``(?#`` (no identical JavaScript meaning, CF-25 m5);
- a literal its own ``pattern`` does not match.

Which file (CF-2): the full one when present, else the public one (the mirror has only that); a
test that needs a withheld record skips it BY NAME. A tree with neither fails. On this repository's
own tree the public fallback is taken ONLY when the tree is the mirror snapshot
(``source_tree.mirror_snapshot``): a full export missing anywhere else fails, so no withheld-record
skip can fire on the private CI.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[3]
FULL = Path("docs") / "legacy-identifiers.md"
PUBLIC = Path("docs") / "legacy-identifiers.public.md"

#: The private organisation's old workbench repository name, for tests that need it as DATA (a
#: planted header, a withheld-record lookup). Built from its parts on purpose: the suite's
#: origin-header gate (``rebrand_checks.py origin-headers``, FR-S001.52) counts every tracked line
#: outside history that spells the joined name, and after P4's header rewrite that count is zero.
OLD_PRIVATE_WORKBENCH = "/".join(("Onegaishimas", "miStudio"))

PHASES = ("P0", "P1", "P2", "P3", "P4", "P5", "P6", "P7", "P8")
FLAGS = frozenset({"history_only", "text_only", "public_withheld", "pending"})
HEADER_KEYS = ("format", "repo", "variant", "register_hash", "phase", "closed", "withheld")
SECTION_KEYS: dict[str, tuple[str, ...]] = {
    "entry": (
        "section",
        "id",
        "kind",
        "group",
        "status",
        "retire_phase",
        "pattern",
        "pattern_js",
        "js_flags",
        "literals",
        "exercise",
        "flags",
    ),
    "env": ("section", "old", "new", "status"),
    "repo": ("section", "old", "new", "status"),
    "host": ("section", "old", "new", "status", "observed"),
    "history_tool": ("section", "old", "new"),
    "guard": (
        "section",
        "id",
        "pattern",
        "pattern_js",
        "js_flags",
        "effect",
        "from_phase",
        "until_phase",
    ),
}
STATUSES = {
    "entry": {"frozen", "scheduled", "retired"},
    "env": {"transition", "retired"},
    "repo": {"transition", "retired"},
    "host": {"transition", "retired"},
}
INLINE_FLAGS = re.compile(r"\(\?[a-zA-Z]+[:)]")
NO_JS_MEANING = (r"\A", r"\Z", "(?P", "(?#")
EXERCISE = re.compile(
    r"^(pytest:(?P<py>[^\s:]+\.py)::(?P<pyfn>\S.*)"
    r"|vitest:(?P<js>[^\s:]+\.(test|spec)\.(ts|tsx|js|jsx))::(?P<jsname>\S.*))$"
)


class ExportError(ValueError):
    """The export is not one this loader understands; the message names the field."""


@dataclass
class Export:
    header: dict[str, Any]
    records: list[dict[str, Any]]
    path: Path | None = None
    withheld_by_name: list[str] = field(default_factory=list)

    @property
    def variant(self) -> str:
        return str(self.header["variant"])

    def section(self, name: str) -> list[dict[str, Any]]:
        return [r for r in self.records if r["section"] == name]

    def entries(self) -> list[dict[str, Any]]:
        return self.section("entry")

    def entry(self, entry_id: str) -> dict[str, Any] | None:
        return next((r for r in self.entries() if r["id"] == entry_id), None)

    def withheld(self) -> list[str]:
        return list(self.header["withheld"])


def _refuse(where: str, message: str) -> ExportError:
    return ExportError(f"{where}: {message}")


def _phase(where: str, key: str, value: object, *, nullable: bool) -> None:
    if value is None and nullable:
        return
    if value not in PHASES:
        raise _refuse(where, f"{key} {value!r} is not a phase name ({', '.join(PHASES)})")


def _check_js(where: str, record: dict[str, Any]) -> None:
    if record["js_flags"] not in ("", "i"):
        raise _refuse(where, f"js_flags {record['js_flags']!r} must be empty or 'i'")
    if INLINE_FLAGS.search(record["pattern_js"]):
        raise _refuse(where, "pattern_js carries an inline flag group (CF-16)")


def _check_pattern(where: str, pattern: str) -> re.Pattern[str]:
    for construct in NO_JS_MEANING:
        if construct in pattern:
            raise _refuse(where, f"pattern uses {construct!r}, which has no JavaScript meaning")
    try:
        return re.compile(pattern)
    except re.error as exc:
        raise _refuse(where, f"pattern does not compile: {exc}") from None


def validate_record(record: dict[str, Any], index: int) -> None:
    section = record.get("section")
    where = f"record {index}"
    if section not in SECTION_KEYS:
        raise _refuse(where, f"unknown section {section!r}")
    where = f"record {index} ({section} {record.get('id') or record.get('old')})"
    expected = SECTION_KEYS[section]
    unknown = sorted(set(record) - set(expected))
    if unknown:
        raise _refuse(where, f"unknown key(s) {unknown}")
    missing = [k for k in expected if k not in record]
    if missing:
        raise _refuse(where, f"missing key(s) {missing}")
    if section in STATUSES and record["status"] not in STATUSES[section]:
        raise _refuse(where, f"status {record['status']!r} not in {sorted(STATUSES[section])}")
    if section == "host" and not isinstance(record["observed"], bool):
        raise _refuse(where, "observed must be true or false (CF-24)")
    if section == "guard":
        if record["effect"] not in ("deny", "allow"):
            raise _refuse(where, f"effect {record['effect']!r} must be deny or allow")
        _phase(where, "from_phase", record["from_phase"], nullable=True)
        _phase(where, "until_phase", record["until_phase"], nullable=True)
        _check_js(where, record)
        _check_pattern(where, record["pattern"])
    if section == "entry":
        flags = record["flags"]
        if not isinstance(flags, list) or set(flags) - FLAGS:
            raise _refuse(where, f"flags {flags!r} outside {sorted(FLAGS)}")
        _phase(where, "retire_phase", record["retire_phase"], nullable=True)
        _check_js(where, record)
        compiled = _check_pattern(where, record["pattern"])
        for literal in record["literals"]:
            if not compiled.search(literal):
                raise _refuse(where, f"literal {literal!r} is not matched by its pattern")
        exercise = record["exercise"]
        if exercise is not None and not EXERCISE.match(exercise):
            raise _refuse(where, f"exercise {exercise!r} is not pytest:<path>::<test>")


def parse(text: str, path: Path | None = None) -> Export:
    match = re.search(r"^```jsonl\n(.*?)^```$", text, flags=re.M | re.S)
    if not match:
        raise ExportError("no ```jsonl block")
    lines = [line for line in match.group(1).splitlines() if line.strip()]
    if not lines:
        raise ExportError("the block is empty")
    header = json.loads(lines[0])
    if header.get("format") != 1:
        raise _refuse("header", f"format {header.get('format')!r} is not 1")
    unknown = sorted(set(header) - set(HEADER_KEYS))
    if unknown:
        raise _refuse("header", f"unknown key(s) {unknown}")
    for key in HEADER_KEYS:
        if key not in header:
            raise _refuse("header", f"missing {key!r}")
    if header["variant"] not in ("full", "public"):
        raise _refuse("header", f"variant {header['variant']!r}")
    _phase("header", "phase", header["phase"], nullable=False)
    _phase("header", "closed", header["closed"], nullable=True)
    records = [json.loads(line) for line in lines[1:]]
    for index, record in enumerate(records, start=1):
        validate_record(record, index)
    return Export(header=header, records=records, path=path)


def load(path: Path | None = None, *, root: Path = REPO) -> Export:
    """The full export when present, else the public one; a tree with neither fails. For this
    repository's own tree the public fallback needs the mirror snapshot (CF-2): the private tree
    must hold the full export."""
    from tests.support.source_tree import mirror_snapshot

    if path is not None:
        return parse(path.read_text(encoding="utf-8"), path)
    if (root / FULL).is_file():
        return parse((root / FULL).read_text(encoding="utf-8"), root / FULL)
    if (root / PUBLIC).is_file():
        if root.resolve() == REPO.resolve() and not mirror_snapshot(root):
            raise ExportError(
                f"{FULL} is missing from {root}, which is not the mirror snapshot: only the mirror "
                f"may read {PUBLIC} in its place (CF-2). Regenerate it with census.py --export."
            )
        return parse((root / PUBLIC).read_text(encoding="utf-8"), root / PUBLIC)
    raise ExportError(f"neither {FULL} nor {PUBLIC} exists under {root}")


def record_id(record: dict[str, Any]) -> set[str]:
    """Every form the ``withheld`` list may name ``record`` by (census ``_wid``)."""
    if record["section"] in ("entry", "guard"):
        return {record["id"]}
    old = str(record["old"])
    digest = hashlib.sha256(old.encode("utf-8")).hexdigest()[:16]
    return {f"{record['section']}:{old}", f"{record['section']}:sha256:{digest}"}


def phase_index(phase: str) -> int:
    return PHASES.index(phase)


def at_least(phase: str | None, other: str) -> bool:
    return phase is not None and phase_index(phase) >= phase_index(other)


def active_guards(export: Export) -> list[dict[str, Any]]:
    """Guard rows in force at the header's ``phase`` (the rules in force; CF-21)."""
    phase = phase_index(export.header["phase"])
    active = []
    for guard in export.section("guard"):
        start, end = guard["from_phase"], guard["until_phase"]
        if start is not None and phase < phase_index(start):
            continue
        if end is not None and phase >= phase_index(end):
            continue
        active.append(guard)
    return active


def enforce_mode_expected(export: Export) -> bool:
    """Enforce mode keys to ``closed`` (CF-21): from P4 closed on."""
    return at_least(export.header["closed"], "P4")


def _compile(pattern: str, flags: str, flavour: str) -> re.Pattern[str]:
    if flavour == "py":
        return re.compile(pattern)
    return re.compile(pattern, re.I if "i" in flags else 0)


def allow_patterns(export: Export, flavour: str = "py") -> list[re.Pattern[str]]:
    """Every allowance the brand guard may use, from the export ONLY (FTID §7.5)."""
    patterns: list[re.Pattern[str]] = []
    for entry in export.entries():
        if entry["status"] in ("frozen", "scheduled"):
            source = entry["pattern"] if flavour == "py" else entry["pattern_js"]
            patterns.append(_compile(source, entry["js_flags"], flavour))
            patterns.extend(re.compile(re.escape(lit)) for lit in entry["literals"])
    for section in ("env", "repo"):
        for row in export.section(section):
            if row["status"] == "transition":
                patterns.append(re.compile(re.escape(row["old"])))
    for row in export.section("host"):
        # An old address in transition (a previous-address list names it until P7), as a whole
        # host name: never as the start of a longer label.
        if row["status"] == "transition":
            patterns.append(
                re.compile(r"(?<![A-Za-z0-9_.-])" + re.escape(row["old"]) + r"(?![A-Za-z0-9_-])")
            )
    for guard in active_guards(export):
        if guard["effect"] == "allow":
            source = guard["pattern"] if flavour == "py" else guard["pattern_js"]
            patterns.append(_compile(source, guard["js_flags"], flavour))
    return patterns


def deny_patterns(export: Export, deny: str, flavour: str = "py") -> list[re.Pattern[str]]:
    """The policy's ``deny`` token plus every active ``deny`` guard."""
    patterns = [re.compile(deny)]
    for guard in active_guards(export):
        if guard["effect"] == "deny":
            source = guard["pattern"] if flavour == "py" else guard["pattern_js"]
            patterns.append(_compile(source, guard["js_flags"], flavour))
    return patterns


def allowed_spans(text: str, export: Export, flavour: str = "py") -> list[tuple[int, int]]:
    spans: list[tuple[int, int]] = []
    for pattern in allow_patterns(export, flavour):
        spans.extend(m.span() for m in pattern.finditer(text) if m.end() > m.start())
    return spans


def _unallowed(
    text: str, export: Export, deny: str, flavour: str = "py"
) -> list[tuple[int, int, str]]:
    """``(start, end, match)`` of every deny match in ``text`` not inside an allowed span."""
    spans = allowed_spans(text, export, flavour)
    found: dict[tuple[int, int], str] = {}
    for pattern in deny_patterns(export, deny, flavour):
        for match in pattern.finditer(text):
            start, end = match.span()
            if not any(a <= start and end <= b for a, b in spans):
                found.setdefault((start, end), match.group(0))
    # One hit per span: the deny token and a deny guard (G-STUDIO) may match the same text.
    return [(start, end, found[(start, end)]) for start, end in sorted(found)]


def unallowed_hits(text: str, export: Export, deny: str, flavour: str = "py") -> list[str]:
    """Every deny match in ``text`` not inside an allowed span."""
    return [hit for _, _, hit in _unallowed(text, export, deny, flavour)]


#: An identifier token: a name a program reads, optionally a kind with its version suffix.
IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_.]*(?:/v?[0-9]+)?")
CODE_SPAN = re.compile(r"`([^`\n]+)`")


def is_identifier_token(token: str, hit: str) -> bool:
    """The scope rule (FPRD Q4, PD-7): identifiers are reported, read surfaces enforced. A token
    is an identifier when it is identifier-shaped, unless it IS the old name in a display form
    (``miLLM``, ``MiStudio``, ``MILLM``: any capital), which is read wherever it stands."""
    if not IDENTIFIER.fullmatch(token):
        return False
    return not (token == hit and hit != hit.lower())


def classified_hits(
    text: str,
    export: Export,
    deny: str,
    flavour: str = "py",
    *,
    whole: bool = True,
    code_spans: bool = True,
) -> tuple[list[str], list[str]]:
    """``(read, identifier)``: the unallowed hits of ``text`` split by scope. ``whole``: ``text``
    is one literal, an identifier when the whole of it is a token. ``code_spans``: a backtick code
    span inside ``text`` holding one token is an identifier too. Both off: everything is read
    (manifest keys and values). The two lists together are exactly :func:`unallowed_hits`."""
    read: list[str] = []
    identifier: list[str] = []
    spans = [(m.start(1), m.end(1)) for m in CODE_SPAN.finditer(text)] if code_spans else []
    for start, end, hit in _unallowed(text, export, deny, flavour):
        token = text if whole else None
        if token is None or not is_identifier_token(token, hit):
            token = next((text[a:b] for a, b in spans if a <= start and end <= b), None)
        if token is not None and is_identifier_token(token, hit):
            identifier.append(hit)
        else:
            read.append(hit)
    return read, identifier


def require_entry(export: Export, entry_id: str) -> dict[str, Any]:
    """The entry, or a skip NAMING it when the public variant withholds it (CF-2). An entry absent
    from a full export is a failure, never a skip."""
    import pytest

    record = export.entry(entry_id)
    if record is not None:
        return record
    if export.variant == "public" and entry_id in export.withheld():
        pytest.skip(f"{entry_id} withheld from the public variant")
    raise AssertionError(f"{entry_id} is not in {export.path}")


def require_repo(export: Export, old: str) -> dict[str, Any]:
    """The ``repo`` record for ``old``, or a skip NAMING it when the public variant withholds it
    (CF-2; the private organisation's pairs are withheld by digest). Absent from a full export is
    a failure, never a skip."""
    import pytest

    for record in export.section("repo"):
        if record["old"] == old:
            return record
    named = sorted(record_id({"section": "repo", "old": old}) & set(export.withheld()))
    if export.variant == "public" and named:
        # Named by the id the export itself uses (a digest for the private pairs).
        pytest.skip(f"{named[0]} withheld from the public variant")
    raise AssertionError(f"repo {old} is not in {export.path}")


def require_host(export: Export, old: str) -> dict[str, Any]:
    """The ``host`` record for ``old``, or a skip NAMING it when the public variant withholds it
    (CF-2: old host names are withheld from the mirror, by digest). Absent from a full export is a
    failure, never a skip."""
    import pytest

    for record in export.section("host"):
        if record["old"] == old:
            return record
    named = sorted(record_id({"section": "host", "old": old}) & set(export.withheld()))
    if export.variant == "public" and named:
        pytest.skip(f"{named[0]} withheld from the public variant")
    raise AssertionError(f"host {old} is not in {export.path}")


def require_guard(export: Export, guard_id: str) -> dict[str, Any]:
    """The guard row, or a skip NAMING it when the public variant withholds it (CF-2;
    ``G-STUDIO-PATH`` names a home path the published-content scan forbids)."""
    import pytest

    for record in export.section("guard"):
        if record["id"] == guard_id:
            return record
    if export.variant == "public" and guard_id in export.withheld():
        pytest.skip(f"{guard_id} withheld from the public variant")
    raise AssertionError(f"{guard_id} is not in {export.path}")
